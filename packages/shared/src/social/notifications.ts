/** The kinds a player is never allowed to silence. */
export const ALWAYS_ON_KINDS: readonly NotificationKind[] = NOTIFICATION_KINDS.filter(
  (kind) => NOTIFICATION_KIND_SPECS[kind].alwaysOn === true,
);

export function isAlwaysOn(kind: NotificationKind): boolean {
  return NOTIFICATION_KIND_SPECS[kind].alwaysOn === true;
}

export const NotificationSchema = z.object({
  id: IdSchema,
  kind: NotificationKindSchema,
  /** The headline, already written by the emitter: a notification is never assembled on the client. */
  title: z.string().min(1),
  /** One line under it. May be empty where the title says the whole thing. */
  body: z.string(),
  /**
   * Where this goes when clicked, as an in-app route.
   *
   * Not optional in practice and not optional in spirit: a receipt you cannot follow back to the
   * thing it is about is the failure mode this whole feature exists to avoid.
   */
  link: z.string().min(1),
  createdAt: IsoDateTimeSchema,
  readAt: IsoDateTimeSchema.nullable(),
});
export type Notification = z.infer<typeof NotificationSchema>;

/**
 * Which kinds this player wants.
 *
 * Stored sparsely: only the kinds explicitly switched **off** are recorded, so a kind added to the
 * catalogue tomorrow is on by default for everybody who has ever touched the settings page. The
 * other way round (record what is on) silently opts every existing player out of every new kind,
 * which reads as a broken feature rather than as a default.
 */
export const NotificationSettingsSchema = z.object({
  muted: z.array(NotificationKindSchema).default([]),
});
export type NotificationSettings = z.infer<typeof NotificationSettingsSchema>;

export function defaultNotificationSettings(): NotificationSettings {
  return { muted: [] };
}

/** Whether a notification of this kind should be written at all for this player. */
export function wantsNotification(settings: NotificationSettings, kind: NotificationKind): boolean {
  return isAlwaysOn(kind) || !settings.muted.includes(kind);
}

/** The settings with one kind flipped. An always-on kind cannot be muted, whatever is asked. */
export function withMuted(
  settings: NotificationSettings,
  kind: NotificationKind,
  muted: boolean,
): NotificationSettings {
  if (isAlwaysOn(kind)) return settings;
  const without = settings.muted.filter((entry) => entry !== kind);
  return { muted: muted ? [...without, kind] : without };
}

export function unreadCount(notifications: readonly Notification[]): number {
  return notifications.filter((entry) => entry.readAt === null).length;
}

/**
 * How a count is drawn on a badge.
 *
 * Capped, because a three-digit number does not fit in a dot beside an icon and a player who has
 * 340 unread is not making a decision on the exact figure.
 */
export const BADGE_MAX = 99;
export function badgeCount(count: number): string {
  return count > BADGE_MAX ? `${BADGE_MAX}+` : String(count);
}
