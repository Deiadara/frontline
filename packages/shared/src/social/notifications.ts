/**
 * Notifications: the game telling you something happened while you were not looking.
 *
 * Modelled on what Grepolis and its neighbours actually do, because the shape is well understood
 * and players arrive already knowing it: a bell with an unread count, a list newest first, a row
 * that marks itself read when you open it, a way to mark everything read, and a settings page that
 * decides which kinds reach you at all.
 *
 * ## A notification is a receipt, not a message
 *
 * Every one of these is generated by the game about something that already happened, and every one
 * carries a **link to the thing it is about**. A notification with nowhere to go is a line of text
 * that makes a player hunt, which is the failure mode of every half-built notification system.
 *
 * ## Kinds are the unit of filtering
 *
 * The settings page is a switch per {@link NotificationKind}, and the *emitter* checks it rather
 * than the reader: a notification a player has switched off is never written. That is the choice
 * with consequences, so it is worth naming. Filtering on read would let somebody turn a category
 * back on and find three weeks of history waiting; filtering on write means the switch is about
 * the future, which is how a player reads it. The unread badge is therefore always a count of
 * things they asked for.
 *
 * ## Groups
 *
 * The settings screen groups the kinds, because thirteen switches in one column is a wall. The
 * groups have no mechanical meaning beyond that.
 */

