  /** One line under it, saying what turning it off would stop. */
  blurb: string;
  /** The icon the row carries in the list. */
  icon: string;
  /**
   * Whether a player can switch it off.
   *
   * Two cannot: a battle report and an attack coming at your district. Those are the game telling
   * you that something irreversible has happened or is about to, and a game that lets you silence
   * that is a game that loses your army while you are reading the market.
   */
